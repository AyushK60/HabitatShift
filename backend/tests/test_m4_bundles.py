"""M4 showcase bundle integrity tests.

Validates the built bundles under ``frontend/public/studies/`` when present:
strict JSON, required schema fields, preview assets that actually exist on
disk, recorded chart series that match the embedded M1 summaries, and the
Himalayan event blocks.  The bundles are generated by
``scripts/build_showcase_bundles.py``; these tests are the independent check
the website relies on.  Skipped (with a clear message) when the bundles have
not been built yet.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parents[2]
STUDIES_ROOT = PROJECT_ROOT / "frontend" / "public" / "studies"

EXPECTED_STUDIES = {
    "coringa_coastal",
    "chilika_wetland",
    "western_ghats_forest",
    "himalaya_purepu_2025",
    "himalaya_langtang_2026",
    "kathmandu_urban",
}

pytestmark = pytest.mark.skipif(
    not STUDIES_ROOT.exists(),
    reason="showcase bundles not built yet (run scripts/build_showcase_bundles.py)",
)


def _load_bundle(study_id: str) -> dict:
    path = STUDIES_ROOT / study_id / "bundle.json"
    if not path.exists():
        pytest.fail(f"bundle.json missing for {study_id}")
    # parse_constant fails the load on NaN/Infinity literals, which browsers
    # reject too
    return json.loads(
        path.read_text(encoding="utf-8"),
        parse_constant=lambda literal: (_ for _ in ()).throw(
            ValueError(f"{study_id}: non-finite JSON literal {literal}")
        ),
    )


@pytest.mark.parametrize("study_id", sorted(EXPECTED_STUDIES))
def test_bundle_schema(study_id: str) -> None:
    bundle = _load_bundle(study_id)
    assert bundle["schema"] == "habitatshift-m4-bundle/1"
    assert bundle["study_id"] == study_id
    assert bundle["evidence_status"] in {"processed", "partial"}
    assert bundle["experiments"], "bundle must embed at least one experiment"
    for experiment in bundle["experiments"]:
        assert experiment["summary"]["periods"], "experiment must have periods"
        assert experiment["summary"]["verification"]["all_passed"]
    assert bundle["georef"]["lonlat_corners"]["upper_left"]
    assert bundle["attribution"]
    assert bundle["interpretation"]["cannot_conclude"], (
        "every bundle must state what the evidence cannot establish"
    )


@pytest.mark.parametrize("study_id", sorted(EXPECTED_STUDIES))
def test_bundle_assets_exist_on_disk(study_id: str) -> None:
    bundle = _load_bundle(study_id)
    assert bundle["assets"], "bundle must reference its preview assets"
    for key, asset in bundle["assets"].items():
        path = STUDIES_ROOT / study_id / asset["path"]
        assert path.exists(), f"missing asset {key} -> {asset['path']}"
        assert len(asset["sha256"]) == 64


def test_threshold_series_matches_recorded_change_blocks() -> None:
    """The interactive charts must show the summaries' own sweep numbers."""
    for study_id in sorted(EXPECTED_STUDIES):
        bundle = _load_bundle(study_id)
        summary = bundle["experiments"][0]["summary"]
        for series in bundle["charts"]["threshold_series"]:
            block = summary["change"][series["index"]]
            recorded = {
                point["threshold"]: point["decrease_percent_of_common"]
                for point in block["thresholds"]
            }
            for point in series["points"]:
                assert recorded[point["threshold"]] == pytest.approx(
                    point["decrease_percent_of_common"]
                ), f"{study_id}/{series['index']} chart diverges from the record"


def test_himalayan_event_blocks() -> None:
    d1 = _load_bundle("himalaya_purepu_2025")
    d2 = _load_bundle("himalaya_langtang_2026")
    assert d1["evidence_status"] == "partial"
    assert d2["evidence_status"] == "processed"
    assert d1["event"]["event_date"] == "2025-07-08"
    assert d2["event"]["event_date"] == "2026-08-26"
    assert d1["event"]["event_mechanism"] != d2["event"]["event_mechanism"], (
        "the two events must keep distinct recorded mechanisms"
    )
    same_day = [
        observation
        for observation in d1["event"]["known_unprocessed_observations"]
        if observation["relative_days"] == 0
    ]
    assert same_day, "D1 must record the same-day acquisition it did not process"


def test_western_ghats_dem_context() -> None:
    bundle = _load_bundle("western_ghats_forest")
    dem = bundle.get("dem_context") or {}
    assert dem.get("available") is True
    assert dem.get("elevation_min_m", 0) < dem.get("elevation_max_m", -1)
