"""Integrity tests for the What-Changed findings output (M4-R1 §15.8).

The findings files are generated by scripts/generate_findings.py from the
frozen M1 difference rasters and embedded in the showcase bundles. These
tests assert the documented invariants so a regeneration can never silently
violate the method contract: minimum mapping unit, area convention, the
common-valid denominator, traceable source rasters and deterministic
per-experiment region IDs.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parents[2]
FINDINGS_DIR = PROJECT_ROOT / "data" / "findings"
BUNDLES_DIR = PROJECT_ROOT / "frontend" / "public" / "studies"

EXPECTED_EXPERIMENTS = {
    "coringa_m1",
    "chilika_m4_dry",
    "chilika_m4_postmonsoon",
    "western_ghats_m4",
    "himalaya_purepu_2025_m4",
    "himalaya_langtang_2026_m4",
    "kathmandu_m4",
}


def _load(name: str) -> dict:
    return json.loads((FINDINGS_DIR / f"{name}.json").read_text(encoding="utf-8"))


@pytest.mark.parametrize("experiment_id", sorted(EXPECTED_EXPERIMENTS))
def test_findings_file_exists_with_schema(experiment_id: str) -> None:
    payload = _load(experiment_id)
    # M4-R2 G4: /2 is a strictly additive evolution of /1 — every /1 field
    # keeps its meaning; see docs/M4_R2_EVIDENCE_SCHEMA.md.
    assert payload["schema"] == "habitatshift-findings/2"
    assert payload["experiment_id"] == experiment_id
    assert payload["study_id"]


@pytest.mark.parametrize("experiment_id", sorted(EXPECTED_EXPERIMENTS))
def test_findings_respect_minimum_mapping_unit(experiment_id: str) -> None:
    payload = _load(experiment_id)
    mmu = payload["method"]["minimum_mapping_unit_px"]
    assert mmu >= 25  # documented floor: 0.25 ha on the 10 m grid
    for finding in payload["findings"]:
        assert finding["pixel_count"] >= mmu


@pytest.mark.parametrize("experiment_id", sorted(EXPECTED_EXPERIMENTS))
def test_findings_area_matches_pixel_count(experiment_id: str) -> None:
    payload = _load(experiment_id)
    for finding in payload["findings"]:
        expected = finding["pixel_count"] * 100.0 / 1e4  # 10 m grid pixel area
        assert finding["area_ha"] == pytest.approx(expected, rel=1e-3)


@pytest.mark.parametrize("experiment_id", sorted(EXPECTED_EXPERIMENTS))
def test_findings_denominator_and_direction(experiment_id: str) -> None:
    payload = _load(experiment_id)
    common = payload["common_valid_pixels"]
    assert common > 0
    for finding in payload["findings"]:
        assert finding["common_valid_pixels"] == common
        assert finding["direction"] in ("decrease", "increase")
        assert 0 < finding["share_of_common_valid_percent"] <= 100


@pytest.mark.parametrize("experiment_id", sorted(EXPECTED_EXPERIMENTS))
def test_findings_traceable_to_source_rasters(experiment_id: str) -> None:
    payload = _load(experiment_id)
    for finding in payload["findings"]:
        assert (PROJECT_ROOT / finding["input_raster"]).exists()
        assert (PROJECT_ROOT / finding["valid_mask"]).exists()
        assert finding["input_raster"].endswith(f"delta_{finding['index']}.tif")


@pytest.mark.parametrize("experiment_id", sorted(EXPECTED_EXPERIMENTS))
def test_findings_have_full_interpretation(experiment_id: str) -> None:
    payload = _load(experiment_id)
    required = (
        "title",
        "location",
        "observation_period",
        "observed_measurement",
        "meaning",
        "explanations",
        "evidence_strength",
        "cannot_conclude",
        "source",
    )
    for finding in payload["findings"]:
        interpretation = finding["interpretation"]
        for key in required:
            assert key in interpretation, f"{experiment_id}: {key} missing"
        assert interpretation["cannot_conclude"], "limitations must be stated"


def test_region_ids_unique_per_experiment() -> None:
    for experiment_id in sorted(EXPECTED_EXPERIMENTS):
        payload = _load(experiment_id)
        ids = [finding["id"] for finding in payload["findings"]]
        assert len(ids) == len(set(ids)), f"{experiment_id}: duplicate region ids"


def test_geometry_is_true_wgs84_polygon() -> None:
    for experiment_id in sorted(EXPECTED_EXPERIMENTS):
        payload = _load(experiment_id)
        for finding in payload["findings"]:
            geometry = finding["geometry_wgs84"]
            assert geometry["type"] == "Polygon"
            ring = geometry["coordinates"][0]
            assert len(ring) >= 4
            assert ring[0] == ring[-1], "polygon ring must close"
            lon, lat = finding["centroid_lonlat"]
            assert -180 <= lon <= 180 and -90 <= lat <= 90


@pytest.mark.parametrize(
    "study_id",
    [
        "coringa_coastal",
        "chilika_wetland",
        "western_ghats_forest",
        "himalaya_purepu_2025",
        "himalaya_langtang_2026",
        "kathmandu_urban",
    ],
)
def test_bundle_embeds_findings_for_first_experiment(study_id: str) -> None:
    bundle = json.loads((BUNDLES_DIR / study_id / "bundle.json").read_text(encoding="utf-8"))
    findings = bundle["experiments"][0].get("findings")
    assert findings is not None, f"{study_id}: bundle lacks findings"
    assert findings["experiment_id"] == bundle["experiments"][0]["experiment_id"]
    on_disk = _load(findings["experiment_id"])
    assert findings["overview"]["findings_total"] == on_disk["overview"]["findings_total"]
